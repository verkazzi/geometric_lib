import math


def area(r):
    '''
    Возвращает произведение квадрата числа r на число π
    (площадь круга радиуса r)

        Параметры:
            r (int или float): число (радиус круга)

        Возвращаемое значение:
            area(float): произведение квадрата числа r на число π (площадь круга)
        
        Пример вызова:
            area(2)
            12.566370614359172

    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возвращает произведение удвоенного числа r на число π
    (длину окружности радиуса r)

        Параметры:
            r (int или float): число (радиус окружности)

        Возвращаемое значение:
            perimeter(float): произведение удвоенного числа r на число π (длина окржуности)
        
        Пример вызова:
            perimeter(2)
            12.566370614359172

    '''
    return 2 * math.pi * r

