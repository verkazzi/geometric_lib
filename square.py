
def area(a):
    '''
    Возвращает квадрат числа a
    (площадь квадрата со сторной длины a)

        Параметры:
            a (int или float): число (длина стороны квадрата )

        Возвращаемое значение:
            area(int или float): квадрат a (площадь квадрата)
        
        Пример вызова:
            area(7)
            49

    '''
    return a * a
    

def perimeter(a):
    '''
    Возвращает произведение числа a и числа 4
    (периметр квадрата со стороной длины a)
        Параметры:
            a(int или float): число (длина стороны квадрата)
        
        Возвращаемое значение:
            perimeter(int или float): произведение a на 4(периметр квадрата с длиной стороной a)
        
        Пример вызова:
            perimeter(10)
            40
    '''
    return 4 * a
